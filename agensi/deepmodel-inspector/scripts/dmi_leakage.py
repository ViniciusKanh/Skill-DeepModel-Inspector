from typing import Any

VERSION = "1.0.0"
SEVERITIES = ("CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO")
STATUSES = ("CONFIRMED", "POTENTIAL", "INCONCLUSIVE")
SEV_RANK = {s: i for i, s in enumerate(SEVERITIES)}


def finding(
    rule: str,
    category: str,
    severity: str,
    status: str,
    title: str,
    evidence: dict[str, Any],
    source: str,
    explanation: str,
    recommendation: str,
    confirmation: str = "",
) -> dict[str, Any]:
    """Cria um achado padronizado. ``status`` CONFIRMED exige regra objetiva satisfeita."""
    assert severity in SEVERITIES and status in STATUSES
    return {
        "id": "",
        "rule": rule,
        "category": category,
        "severity": severity,
        "status": status,
        "title": title,
        "evidence": evidence,
        "source": source,
        "explanation": explanation,
        "recommendation": recommendation,
        "confirmation": confirmation,
    }


def result(
    analysis: str,
    source: str,
    metrics: dict[str, Any],
    findings: list[dict[str, Any]],
    limitations: list[str],
    **extra: Any,
) -> dict[str, Any]:
    """Monta o resultado de uma análise e numera os achados de forma determinística."""
    prefix = analysis[:3].upper()
    findings = sorted(findings, key=lambda f: (SEV_RANK[f["severity"]], f["rule"]))
    for i, f in enumerate(findings, 1):
        f["id"] = f"{prefix}-{i:03d}"
    out = {
        "tool": "deepmodel-inspector",
        "version": VERSION,
        "analysis": analysis,
        "source": source,
        "metrics": metrics,
        "findings": findings,
        "limitations": limitations,
    }
    out.update(extra)
    return out


