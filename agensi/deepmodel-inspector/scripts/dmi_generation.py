DECODING = ("temperature", "top_k", "top_p", "repetition_penalty", "max_tokens", "max_new_tokens", "do_sample")
WORD = re.compile(r"\w+", re.UNICODE)
SENT = re.compile(r"(?<=[.!?。])\s+|\n+")
