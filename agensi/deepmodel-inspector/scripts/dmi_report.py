# ============================================================== security/guard.py
import os
from pathlib import Path

# Nomes/extensões que nunca são lidos (credenciais e segredos).
SENSITIVE_NAMES = {
    ".env",
    ".netrc",
    ".pgpass",
    ".git-credentials",
    "credentials",
    "credentials.json",
    "id_rsa",
    "id_dsa",
    "id_ecdsa",
    "id_ed25519",
    "known_hosts",
    "authorized_keys",
    ".npmrc",
    ".pypirc",
    "secrets.json",
    "secrets.yaml",
    "secrets.yml",
    "token.json",
}
SENSITIVE_SUFFIXES = {".pem", ".key", ".p12", ".pfx", ".keystore", ".jks", ".kdbx"}
SENSITIVE_DIRS = {".ssh", ".aws", ".gnupg", ".azure", ".kube", ".docker", ".config/gcloud"}
# Formatos cuja leitura exigiria desserialização insegura (pickle) ou binários de pesos.
UNSAFE_DESERIALIZATION = {".pkl", ".pickle", ".pt", ".pth", ".ckpt", ".bin", ".joblib", ".npy", ".npz"}
DEFAULT_MAX_MB = 200.0


class SecurityError(Exception):
    """Erro levantado quando uma operação viola a política de segurança."""


def _roots(allowed_roots: list[str] | None) -> list[Path]:
    """Resolve as raízes autorizadas (padrão: somente o diretório corrente).

    Variáveis de ambiente não são lidas, por política de privacidade.
    """
    raw = list(allowed_roots or []) or [os.getcwd()]
    return [Path(r).expanduser().resolve() for r in raw]


def is_sensitive(path: Path) -> bool:
    """Indica se o caminho aponta para credenciais ou diretórios de segredos."""
    name = path.name.lower()
    if name in SENSITIVE_NAMES or name.startswith(".env.") and name != ".env.example":
        return True
    if path.suffix.lower() in SENSITIVE_SUFFIXES:
        return True
    parts = [p.lower() for p in path.parts]
    joined = "/".join(parts)
    return any(d in parts or f"/{d}/" in f"/{joined}/" for d in SENSITIVE_DIRS)


def within_roots(path: Path, roots: list[Path]) -> bool:
    """Verifica se ``path`` (já resolvido) está contido em alguma raiz autorizada."""
    for root in roots:
        try:
            path.relative_to(root)
            return True
        except ValueError:
            continue
    return False


def safe_input_path(
    path: str | os.PathLike[str],
    allowed_roots: list[str] | None = None,
    max_mb: float = DEFAULT_MAX_MB,
    allow_dir: bool = False,
) -> Path:
    """Valida um caminho de entrada (somente leitura) e devolve o caminho resolvido.

    Regras: deve existir, estar dentro das raízes autorizadas, não ser sensível,
    não exigir desserialização insegura e respeitar o limite de tamanho.
    """
    p = Path(path).expanduser().resolve()
    roots = _roots(allowed_roots)
    if not within_roots(p, roots):
        raise SecurityError(f"path outside authorized roots: {p}")
    if is_sensitive(p):
        raise SecurityError(f"refusing to read sensitive file: {p.name}")
    if not p.exists():
        raise FileNotFoundError(f"path not found: {p}")
    if p.is_dir():
        if not allow_dir:
            raise SecurityError(f"expected a file, got a directory: {p}")
        return p
    if p.suffix.lower() in UNSAFE_DESERIALIZATION:
        raise SecurityError(f"unsafe deserialization refused for {p.suffix} files: {p.name}")
    size_mb = p.stat().st_size / (1024 * 1024)
    if size_mb > max_mb:
        raise SecurityError(f"file exceeds size limit ({size_mb:.1f} MB > {max_mb} MB): {p.name}")
    return p


def safe_output_path(
    path: str | os.PathLike[str],
    inputs: list[Path] | None = None,
    allowed_roots: list[str] | None = None,
) -> Path:
    """Valida um caminho de saída: nunca sobrescreve entradas nem escreve fora das raízes."""
    p = Path(path).expanduser().resolve()
    roots = _roots(allowed_roots)
    if not within_roots(p, roots):
        raise SecurityError(f"output outside authorized roots: {p}")
    if is_sensitive(p):
        raise SecurityError(f"refusing to write sensitive path: {p.name}")
    for src in inputs or []:
        if p == src.resolve():
            raise SecurityError(f"refusing to overwrite an analyzed input: {p.name}")
    return p

# ============================================================== reporting/render.py
import html
import json
from typing import Any

LABELS = {
    "en": [
        "Executive Summary",
        "Data & Artifact Inventory",
        "Training Health",
        "Dataset Quality",
        "Tokenizer Efficiency",
        "Generation Behavior",
        "Experiment Comparison",
        "Root Cause Investigation",
        "Findings by Severity",
        "Recommended Experiments",
        "Evidence & Limitations",
    ],
    "pt": [
        "Resumo Executivo",
        "Inventário de Dados e Artefatos",
        "Saúde do Treinamento",
        "Qualidade do Dataset",
        "Eficiência do Tokenizer",
        "Comportamento de Geração",
        "Comparação de Experimentos",
        "Investigação de Causa Raiz",
        "Achados por Severidade",
        "Experimentos Recomendados",
        "Evidências e Limitações",
    ],
}
SECTION_KEYS = [
    None,
    None,
    ("training", "checkpoint"),
    ("dataset", "leakage"),
    ("tokenizer",),
    ("generation",),
    ("comparison",),
    None,
    None,
    None,
    None,
]
NOT_RUN = {
    "en": "Not analyzed (no matching artifact provided).",
    "pt": "Não analisado (nenhum artefato correspondente).",
}


def _md(x: Any) -> str:
    """Neutraliza texto para Markdown (pipes, quebras e crases)."""
    return str(x).replace("|", "\\|").replace("\n", " ").replace("`", "'")


def _brief(metrics: dict[str, Any], limit: int = 900) -> str:
    """Métricas em JSON compacto e truncado para leitura."""
    s = json.dumps(metrics, ensure_ascii=False, default=str)
    return s if len(s) <= limit else s[:limit] + " …"


def to_markdown(rep: dict[str, Any], lang: str = "en") -> str:
    """Relatório Markdown com as 11 seções padronizadas."""
    L = LABELS.get(lang, LABELS["en"])
    fid = {f["id"]: f for f in rep.get("findings", [])}
    out = [
        "# DeepModel Inspector Report",
        "",
        f"Version {rep.get('version')} · generated {rep.get('generated_at')} · analyses: "
        f"{', '.join(rep.get('analyses_run', [])) or 'none'}",
        "",
    ]
    s = rep.get("summary", {})
    out += [f"## 1. {L[0]}", ""]
    if rep.get("question"):
        a = rep.get("answer", {})
        out += [
            f"**Question:** {_md(rep['question'])}",
            "",
            f"**Answer status:** `{a.get('status')}` — {_md(a.get('conclusion', ''))}",
            "",
        ]
    out += [
        f"- Findings by severity: {s.get('findings_by_severity')}",
        f"- Findings by status: {s.get('findings_by_status')}",
    ]
    out += [f"- {_md(t)}" for t in s.get("top_findings", [])] + [""]
    out += [f"## 2. {L[1]}", "", "| Analysis | Source |", "|---|---|"]
    out += [
        f"| {_md(i.get('kind') or i.get('analysis'))} | {_md(i.get('source') or i.get('path'))} |"
        for i in rep.get("inventory", [])
    ]
    out.append("")
    for n in range(2, 7):
        out += [f"## {n + 1}. {L[n]}", ""]
        blocks = [b for k in SECTION_KEYS[n] for b in rep.get("sections", {}).get(k, [])]
        if not blocks:
            out += [NOT_RUN.get(lang, NOT_RUN["en"]), ""]
        for b in blocks:
            out += [f"**Source:** `{_md(b.get('source'))}`", "", f"Metrics: `{_md(_brief(b.get('metrics', {})))}`", ""]
            ids = b.get("finding_ids", [])
            out += [f"- {i} [{fid[i]['severity']}/{fid[i]['status']}] {_md(fid[i]['title'])}" for i in ids if i in fid]
            out.append("")
    out += [f"## 8. {L[7]}", ""]
    hyps = rep.get("hypotheses", [])
    if not hyps:
        out += ["No cross-artifact hypothesis was triggered by the evidence.", ""]
    for h in hyps:
        out += [
            f"- **{h['id']}** `{h['status']}` {_md(h['statement'])} (supported by {', '.join(h['supporting_findings'])})",
            f"  - Test: {_md(h['experiment'])}",
        ]
    a = rep.get("answer")
    if a and a.get("missing_artifacts"):
        out += ["", "Missing artifacts to answer the question:"] + [
            f"- {_md(m['provide'])}" for m in a["missing_artifacts"]
        ]
    out += ["", f"## 9. {L[8]}", ""]
    for f in rep.get("findings", []):
        out += [
            f"### {f['id']} · {f['severity']} · {f['status']} · {_md(f['title'])}",
            "",
            f"- Rule: `{f['rule']}` · Category: {f['category']} · Source: `{_md(f['source'])}`",
            f"- Evidence: `{_md(_brief(f['evidence'], 600))}`",
            f"- Explanation: {_md(f['explanation'])}",
            f"- Recommendation: {_md(f['recommendation'])}",
        ]
        if f.get("confirmation"):
            out.append(f"- How to confirm: {_md(f['confirmation'])}")
        out.append("")
    out += [f"## 10. {L[9]}", ""]
    out += [f"{e['priority']}. ({e['for']}) {_md(e['experiment'])}" for e in rep.get("experiments", [])] or ["None."]
    out += [
        "",
        f"## 11. {L[10]}",
        "",
        "Statuses: CONFIRMED = rule satisfied by the data; POTENTIAL = indicators support a possible problem; "
        "INCONCLUSIVE = insufficient information. Hypotheses are never presented as confirmed causes.",
        "",
    ]
    out += [f"- {_md(x)}" for x in rep.get("limitations", [])]
    return "\n".join(out) + "\n"


def _svg(series: dict[str, list[list[float]]], w: int = 560, h: int = 180) -> str:
    """Gráfico SVG de linhas (apenas quando há séries reais)."""
    pts = [p for v in series.values() for p in v]
    if len(pts) < 2:
        return ""
    x0, x1 = min(p[0] for p in pts), max(p[0] for p in pts)
    y0, y1 = min(p[1] for p in pts), max(p[1] for p in pts)
    sx = (w - 40) / ((x1 - x0) or 1)
    sy = (h - 30) / ((y1 - y0) or 1)
    colors = {"train_loss": "#2563eb", "val_loss": "#dc2626"}
    lines = []
    for name, v in series.items():
        d = " ".join(f"{30 + (x - x0) * sx:.1f},{h - 20 - (y - y0) * sy:.1f}" for x, y in v)
        lines.append(
            f'<polyline fill="none" stroke="{colors.get(name, "#555")}" stroke-width="1.5" points="{d}"/>'
            f'<text x="{w - 110}" y="{14 + 14 * len(lines)}" fill="{colors.get(name, "#555")}" font-size="11">{html.escape(name)}</text>'
        )
    return (
        f'<svg viewBox="0 0 {w} {h}" width="100%" role="img" aria-label="loss curves">'
        f'<text x="2" y="12" font-size="10">{y1:.3g}</text><text x="2" y="{h - 20}" font-size="10">{y0:.3g}</text>'
        f'<text x="30" y="{h - 4}" font-size="10">step {x0:g}</text><text x="{w - 70}" y="{h - 4}" font-size="10">{x1:g}</text>'
        + "".join(lines)
        + "</svg>"
    )


def to_html(rep: dict[str, Any], lang: str = "en") -> str:
    """HTML estático autocontido; Markdown convertido de forma simples e escapado."""
    body = []
    for line in to_markdown(rep, lang).splitlines():
        e = html.escape(line)
        if line.startswith("### "):
            body.append(f"<h3>{e[4:]}</h3>")
        elif line.startswith("## "):
            body.append(f"<h2>{e[3:]}</h2>")
        elif line.startswith("# "):
            body.append(f"<h1>{e[2:]}</h1>")
        elif line.startswith(("- ", "  - ")):
            body.append(f"<li>{e.lstrip(' -')}</li>")
        elif line.startswith("|"):
            body.append(f"<pre>{e}</pre>")
        elif line.strip():
            body.append(f"<p>{e}</p>")
        if line.startswith("## 3."):
            for b in rep.get("sections", {}).get("training", []):
                if b.get("series"):
                    body.append(_svg(b["series"]))
    css = (
        "body{font-family:system-ui,sans-serif;max-width:980px;margin:24px auto;padding:0 16px;color:#111;"
        "background:#fff}h2{border-bottom:1px solid #ddd;padding-bottom:4px}li{margin:2px 0}"
        "pre{margin:0;font-size:12px;white-space:pre-wrap}p,li{font-size:14px;line-height:1.45}"
    )
    return (
        f'<!doctype html><html lang="{lang}"><head><meta charset="utf-8"><meta name="viewport" '
        f'content="width=device-width,initial-scale=1"><title>DeepModel Inspector Report</title><style>{css}</style>'
        f"</head><body>{''.join(body)}</body></html>\n"
    )


# ============================================================== entry point
def _main() -> int:
    import argparse
    import json as _json
    import sys as _sys

    ap = argparse.ArgumentParser(description="Render a consolidated report JSON (from dmi_investigate.py) as Markdown/HTML.")
    ap.add_argument("--input", "-i", required=True)
    ap.add_argument("--format", "-f", choices=("markdown", "html"), default="markdown")
    ap.add_argument("--lang", choices=("en", "pt"), default="en")
    ap.add_argument("--output", "-o")
    ap.add_argument("--root", action="append")
    a = ap.parse_args()
    try:
        p = safe_input_path(a.input, a.root, 200.0)
        rep = _json.loads(p.read_text(encoding="utf-8"))
        if not isinstance(rep, dict) or "summary" not in rep or "findings" not in rep:
            raise ValueError("input is not a consolidated report (run dmi_investigate.py first)")
        text = to_markdown(rep, a.lang) if a.format == "markdown" else to_html(rep, a.lang)
        if a.output:
            out = safe_output_path(a.output, [p], a.root)
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text, encoding="utf-8")
            print(f"wrote {out}")
        else:
            _sys.stdout.write(text)
        return 0
    except SecurityError as exc:
        print(f"security: {exc}", file=_sys.stderr)
        return 3
    except (ValueError, OSError, UnicodeError) as exc:
        print(f"error: {exc}", file=_sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(_main())
